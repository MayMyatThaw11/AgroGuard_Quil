from datetime import UTC, datetime, timedelta
from typing import Any

import httpx
from pydantic import SecretStr

BASE = "/api/v1/agriquill"
REQUEST_TIMEOUT_S = 60.0
LOTS_PER_FARM = 2
CERTS_PER_FARM = 2
READINGS_PER_LOT = 3
OPEN_METEO_HOST = "api.open-meteo.com"
YANGON_OFFSET_S = 23400
BOT = "LoadBot"


def farm_ids(farms: int, tag: str) -> list[str]:
    return [f"synthetic_load_{tag}{n:04d}" for n in range(farms)]


def plot_counts(farms: int, plots: int) -> list[int]:
    base, extra = divmod(max(plots, farms), farms)
    return [base + (1 if n < extra else 0) for n in range(farms)]


def contract_text(farm_id: str, n: int, plots: int) -> str:
    lat, lon = 16.0 + (n % 100) * 0.02, 95.0 + (n // 100) * 0.05
    parcels = "\n".join(
        f'parcel P{k} {{\n    area: 0.5 ha\n    crop_id: rice_lowland\n    crop: "rice"\n'
        f'    stage: Tillering\n    planted: "2026-09-01"\n}}\n'
        for k in range(plots)
    )
    serves = ", ".join(f"P{k}" for k in range(plots))
    return (
        f"// Synthetic farm generated by the load harness; not a real farm.\n"
        f'farm {farm_id} {{\n    name: "Synthetic load farm {n}"\n    country: MM\n'
        f"    location: [{lat:.2f}, {lon:.2f}]\n    standard: EU_2018_848\n}}\n"
        f"{parcels}"
        f'asset P-01 {{ kind: pump label: "Synthetic pump" serves: [{serves}] }}\n'
    )


def _fixed_days(count: int, rain: float, rh: float) -> list[dict[str, float]]:
    return [{"rain_mm": rain, "temp_c": 29.0, "rh_pct": rh, "wind_ms": 2.5}] * count


def ops_body(farm_id: str, plots: int) -> dict[str, Any]:
    paddies = [
        {
            "id": f"P{k}",
            "crop_id": "rice_lowland",
            "stage": "Tillering",
            "days_since_planting": 45,
            "area_ha": 0.5,
            "water_depth_cm": [3.0, 2.0, 1.0, 0.0, -2.0, -4.0, -6.0, -8.0, -9.0, -10.0],
            "ndvi": [0.7] * 10,
        }
        for k in range(min(plots, 3))
    ]
    return {
        "farm_id": farm_id,
        "country": "MM",
        "standard": "EU_2018_848",
        "start_date": "2026-10-10",
        "paddies": paddies,
        "weather_history": _fixed_days(10, 2.0, 80.0),
        "weather_forecast": _fixed_days(7, 4.0, 90.0),
    }


PERSONAS = {
    "variations": [
        {"persona": "manual", "crew": 2},
        {"persona": "tech", "crew": 2, "machines": ["P-01"]},
    ]
}


def synthetic_open_meteo(request: httpx.Request) -> dict[str, Any]:
    params = request.url.params
    past, ahead = int(params.get("past_days", "14")), int(params.get("forecast_days", "8"))
    local_now = datetime.now(UTC) + timedelta(seconds=YANGON_OFFSET_S)
    start = datetime.combine(local_now.date() - timedelta(days=past), datetime.min.time())
    hours = [start + timedelta(hours=h) for h in range((past + ahead) * 24)]
    day = [1 if 6 <= t.hour < 18 else 0 for t in hours]
    temp = [round(27.0 + 4.0 * math.sin((t.hour - 9) / 24 * 2 * math.pi), 1) for t in hours]
    return {
        "synthetic": "load harness stub, not Open-Meteo data",
        "latitude": float(params.get("latitude", "0")),
        "longitude": float(params.get("longitude", "0")),
        "timezone": "Asia/Yangon",
        "utc_offset_seconds": YANGON_OFFSET_S,
        "elevation": 10.0,
        "hourly_units": {"temperature_2m": "°C", "precipitation": "mm", "wind_speed_10m": "m/s"},
        "hourly": {
            "time": [t.strftime("%Y-%m-%dT%H:%M") for t in hours],
            "temperature_2m": temp,
            "relative_humidity_2m": [85.0] * len(hours),
            "wet_bulb_temperature_2m": [round(t - 3.0, 1) for t in temp],
            "precipitation": [0.4 if t.hour == 15 else 0.0 for t in hours],
            "wind_speed_10m": [2.0] * len(hours),
            "wind_gusts_10m": [4.0] * len(hours),
            "et0_fao_evapotranspiration": [0.2 * d for d in day],
            "is_day": day,
        },
    }


class OutsideStub:
    """Answers every outside HTTP call: synthetic hourly weather for Open-Meteo, 503 elsewhere."""

    def __init__(self) -> None:
        self.calls: Counter[str] = Counter()

    def answer(self, request: httpx.Request) -> httpx.Response:
        host = request.url.host
        self.calls[host] += 1
        if host == OPEN_METEO_HOST and request.url.path == "/v1/forecast":
            return httpx.Response(200, json=synthetic_open_meteo(request), request=request)
        return httpx.Response(503, text="stubbed by the load harness", request=request)

    @contextmanager
    def installed(self) -> Iterator[None]:
        sync, aio = (
            httpx.HTTPTransport.handle_request,
            httpx.AsyncHTTPTransport.handle_async_request,
        )

        def handle(_: httpx.HTTPTransport, request: httpx.Request) -> httpx.Response:
            return self.answer(request)

        async def handle_async(
            _: httpx.AsyncHTTPTransport, request: httpx.Request
        ) -> httpx.Response:
            return self.answer(request)

        httpx.HTTPTransport.handle_request = handle  # type: ignore[method-assign]
        httpx.AsyncHTTPTransport.handle_async_request = handle_async  # type: ignore[method-assign]
        try:
            yield
        finally:
            httpx.HTTPTransport.handle_request = sync  # type: ignore[method-assign]
            httpx.AsyncHTTPTransport.handle_async_request = aio  # type: ignore[method-assign]


class Runner:
    def __init__(self, client: httpx.AsyncClient, concurrency: int) -> None:
        self.client = client
        self.slots = asyncio.Semaphore(concurrency)
        self.latency: dict[str, list[float]] = defaultdict(list)
        self.statuses: Counter[str] = Counter()
        self.failures: list[str] = []

    async def call(self, name: str, method: str, path: str, **kwargs: Any) -> httpx.Response | None:
        async with self.slots:
            started = time.perf_counter()
            try:
                res = await asyncio.wait_for(
                    self.client.request(method, BASE + path, **kwargs), REQUEST_TIMEOUT_S
                )
            except (TimeoutError, httpx.HTTPError) as exc:
                self.statuses[type(exc).__name__] += 1
                self.failures.append(f"{name} {path}: {type(exc).__name__}")
                return None
            self.latency[name].append((time.perf_counter() - started) * 1000)
            self.statuses[str(res.status_code)] += 1
            if res.status_code >= 400:
                self.failures.append(f"{name} {path}: {res.status_code} {res.text[:160]}")
            return res

    async def phase(self, jobs: list[tuple[Any, ...]], rng: random.Random) -> None:
        rng.shuffle(jobs)
        await asyncio.gather(
            *(self.call(*job[:3], **(job[3] if len(job) > 3 else {})) for job in jobs)
        )


def _pct(values: list[float], q: float) -> float | None:
    if not values:
        return None
    ordered = sorted(values)
    return round(ordered[min(len(ordered) - 1, math.ceil(q * len(ordered)) - 1)], 1)


def _reads(farm: str) -> list[tuple[Any, ...]]:
    return [
        ("flows", "GET", f"/contracts/{farm}/flows"),
        ("harvest_reference", "GET", f"/contracts/{farm}/harvest-reference"),
        ("certificates_list", "GET", f"/farms/{farm}/certificates"),
        ("lots_list", "GET", f"/farms/{farm}/lots"),
    ]


async def drive(
    client: httpx.AsyncClient, farms: int, plots: int, concurrency: int, tag: str = ""
) -> dict[str, Any]:
    rng = random.Random(20261022)
    runner = Runner(client, concurrency)
    ids = farm_ids(farms, tag)
    sizes = plot_counts(farms, plots)
    started = time.perf_counter()
    await runner.phase(
        [
            (
                "contract_put",
                "PUT",
                f"/contracts/{farm}",
                {"json": {"text": contract_text(farm, n, sizes[n]), "registered_by": BOT}},
            )
            for n, farm in enumerate(ids)
        ],
        rng,
    )
    writes: list[tuple[Any, ...]] = []
    for n, farm in enumerate(ids):
        for k in range(CERTS_PER_FARM):
            cert = {
                "kind": "gap",
                "number": f"SYN-{n}-{k}",
                "issuer": "Synthetic issuer",
                "country": "MM",
                "issued": "2026-01-01",
                "expires": "2027-06-30",
                "added_by": BOT,
            }
            writes.append(
                ("certificate_add", "POST", f"/farms/{farm}/certificates", {"json": cert})
            )
        for k in range(LOTS_PER_FARM):
            lot = {
                "id": f"L{k}",
                "parcels": [f"P{k % sizes[n]}"],
                "harvested_on": "2026-10-20",
                "mass_kg": 900.0,
                "recorded_by": BOT,
            }
            writes.append(("lot_add", "POST", f"/farms/{farm}/lots", {"json": lot}))
        writes += _reads(farm)
        writes.append(
            ("persona_plan", "POST", f"/contracts/{farm}/persona-plan", {"json": PERSONAS})
        )
        writes.append(("ops_plan", "POST", "/ops/plan", {"json": ops_body(farm, sizes[n])}))
    await runner.phase(writes, rng)
    readings: list[tuple[Any, ...]] = []
    for farm in ids:
        for k in range(LOTS_PER_FARM):
            for r in range(READINGS_PER_LOT):
                body = {
                    "measured_at": f"2026-10-21T0{r}:00:00+06:30",
                    "moisture_pct": 20.0 - r,
                    "drying_method": "sun",
                    "recorded_by": BOT,
                }
                path = f"/farms/{farm}/lots/L{k}/moisture"
                readings.append(("moisture_add", "POST", path, {"json": body}))
        readings += _reads(farm)
    await runner.phase(readings, rng)
    elapsed = time.perf_counter() - started
    checks = await verify(runner, ids)
    every = [v for values in runner.latency.values() for v in values]
    return {
        "farms": farms,
        "plots": sum(sizes),
        "concurrency": concurrency,
        "requests": len(every),
        "seconds": round(elapsed, 1),
        "latency_ms": {"p50": _pct(every, 0.5), "p95": _pct(every, 0.95), "p99": _pct(every, 0.99)},
        "by_route_ms": {
            name: {"n": len(v), "p50": _pct(v, 0.5), "p95": _pct(v, 0.95), "p99": _pct(v, 0.99)}
            for name, v in sorted(runner.latency.items())
        },
        "statuses": dict(sorted(runner.statuses.items())),
        "errors_by_status": {s: n for s, n in runner.statuses.items() if not s.startswith("2")},
        "failures": runner.failures[:20],
        "checks": checks,
    }


async def verify(runner: Runner, ids: list[str]) -> dict[str, Any]:
    certs = lots = readings = 0
    for farm in ids:
        got = await runner.call(
            "verify", "GET", f"/farms/{farm}/certificates", params={"limit": 500}
        )
        certs += got.json()["total"] if got is not None and got.status_code == 200 else 0
        got = await runner.call("verify", "GET", f"/farms/{farm}/lots", params={"limit": 500})
        if got is not None and got.status_code == 200:
            rows = got.json()["lots"]
            lots += len(rows)
            readings += sum(len(lot["moisture"]) for lot in rows)
    ledger = await runner.call("verify", "GET", "/ledger")
    entries = ledger.json()["entries"] if ledger is not None and ledger.status_code == 200 else []
    kinds = Counter(e["kind"] for e in entries)
    expected = {
        "certificates": len(ids) * CERTS_PER_FARM,
        "lots": len(ids) * LOTS_PER_FARM,
        "moisture_readings": len(ids) * LOTS_PER_FARM * READINGS_PER_LOT,
    }
    found = {"certificates": certs, "lots": lots, "moisture_readings": readings}
    server_errors = sum(n for s, n in runner.statuses.items() if s.startswith("5"))
    intact = bool(ledger is not None and ledger.status_code == 200 and ledger.json()["valid"])
    return {
        "expected_writes": expected,
        "read_back": found,
        "no_lost_write": found == expected,
        "ledger_writes": {
            "certificate_recorded": kinds["certificate_recorded"],
            "harvest": kinds["harvest"],
            "lot_moisture": kinds["lot_moisture"],
        },
        "ledger_intact": intact,
        "server_errors": server_errors,
        "ok": found == expected and server_errors == 0 and intact,
    }


@contextmanager
def isolated_app(token: str) -> Iterator[Any]:
    from agriquill import store
    from agriquill.api.main import create_app
    from agriquill.config import get_settings

    settings = get_settings()
    saved = (
        settings.data_dir,
        settings.ledger_path,
        settings.users,
        settings.write_token,
        settings.builtin_user,
    )
    with tempfile.TemporaryDirectory(prefix="agriquill-load-") as tmp:
        store.close_all()
        settings.data_dir = os.path.join(tmp, "data")
        settings.ledger_path = os.path.join(tmp, "data", "ledger.jsonl")
        settings.users = SecretStr(f"{BOT}:{token}:crew,manager")
        settings.write_token = None
        settings.builtin_user = None
        try:
            yield create_app()
        finally:
            store.close_all()
            (
                settings.data_dir,
                settings.ledger_path,
                settings.users,
                settings.write_token,
                settings.builtin_user,
            ) = saved


async def run_in_process(farms: int, plots: int, concurrency: int) -> dict[str, Any]:
    token = secrets.token_hex(16)
    stub = OutsideStub()
    with isolated_app(token) as app, stub.installed():
        transport = httpx.ASGITransport(app=app)
        async with httpx.AsyncClient(
            transport=transport,
            base_url="http://load.test",
            headers={"X-AgriQuill-Write-Token": token},
            timeout=REQUEST_TIMEOUT_S,
        ) as client:
            out = await drive(client, farms, plots, concurrency)
    total = sum(stub.calls.values())
    out["outside_calls"] = {
        "total": total,
        "per_farm": round(total / farms, 2),
        "by_host": dict(stub.calls),
    }
    return out


async def run_against(
    url: str, token: str, farms: int, plots: int, concurrency: int
) -> dict[str, Any]:
    async with httpx.AsyncClient(
        base_url=url, headers={"X-AgriQuill-Write-Token": token}, timeout=REQUEST_TIMEOUT_S
    ) as client:
        out = await drive(client, farms, plots, concurrency, f"{secrets.token_hex(3)}_")
    out["outside_calls"] = {"total": None, "reason": "not counted against a remote server"}
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--farms", type=int, default=200)
    parser.add_argument("--plots", type=int, default=500, help="plots across all farms")
    parser.add_argument("--concurrency", type=int, default=50)
    parser.add_argument("--url", help="run against this server instead of in process")
    args = parser.parse_args()
    if args.url:
        token = os.environ.get("AGRIQUILL_LOAD_TOKEN", "")
        report = asyncio.run(run_against(args.url, token, args.farms, args.plots, args.concurrency))
    else:
        report = asyncio.run(run_in_process(args.farms, args.plots, args.concurrency))
    print(json.dumps(report, indent=2, default=str))
    raise SystemExit(0 if report["checks"]["ok"] else 1)


if __name__ == "__main__":
    main()
