"""Load test for the farm map backend on synthetic farms.

In process (default) the app runs on a throwaway data folder and every outside HTTP call is
answered by a counting stub, so the run measures our code and caches, not the network.
With --url it drives a running server instead; outside calls are then not stubbed or counted.

    python scripts/load_farm_map.py --farms 200 --plots 500 --concurrency 50
"""

