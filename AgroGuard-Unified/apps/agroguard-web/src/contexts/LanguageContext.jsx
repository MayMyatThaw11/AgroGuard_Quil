export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState('en');

  // Screen readers and the browser's font choice follow the page language.
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  // `params` is optional and only used by a few new Fertilizer/Water/
  // Satellite/Export strings that need a number inline (e.g. "2 of 7
  // items missing") — every existing single-argument call is unaffected.
  const t = (key, params) => {
    const raw = translations[language][key] || translations['en'][key] || key;
    if (!params) return raw;
    return Object.entries(params).reduce(
      (str, [paramKey, value]) => str.replaceAll(`{${paramKey}}`, value),
      raw,
    );
  };

  const toggleLanguage = () => {
    setLanguage(prev => prev === 'en' ? 'my' : 'en');
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, toggleLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
